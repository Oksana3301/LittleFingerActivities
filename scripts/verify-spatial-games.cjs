const fs=require('fs'),path=require('path'),vm=require('vm'),ts=require('typescript'),assert=require('assert/strict');
const root=path.resolve(__dirname,'..'),moduleValue={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(path.join(root,'app/data/spatial-games.ts'),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{module:moduleValue,exports:moduleValue.exports});
const {placePiece,spatialComplete}=moduleValue.exports;
const records=JSON.parse(fs.readFileSync(path.join(root,'public/worksheets/spatial-layouts.json'))),layout={...records[0],...records[0].rounds[0]};
let sorted=placePiece(layout,{},'o0','cell-0');
assert.equal(spatialComplete(layout,{sorted}),false);
sorted=placePiece(layout,sorted,'o1','cell-0');
assert.equal(sorted.o0,undefined);assert.equal(sorted.o1,'cell-0');
sorted=placePiece(layout,sorted,'o1','cell-1');
assert.equal(Object.keys(sorted).length,1);assert.equal(sorted.o1,'cell-1');
assert.equal(placePiece(layout,sorted,'unknown','cell-0'),sorted);
assert.equal(placePiece(layout,sorted,'o0','cell-99'),sorted);
const solved=Object.fromEntries(layout.pairs.map(p=>[p.left,p.right]));
assert.equal(spatialComplete(layout,{sorted:solved}),true);
const routeRecord=JSON.parse(fs.readFileSync(path.join(root,'public/worksheets/route-adventures.json')))[0],route={...routeRecord,...routeRecord.rounds[0]};
assert.equal(spatialComplete(route,{selected:[route.answer.at(-1)]}),false);
assert.equal(spatialComplete(route,{selected:[...route.answer].reverse()}),false);
assert.equal(spatialComplete(route,{selected:route.answer}),true);
const puzzleRecord=JSON.parse(fs.readFileSync(path.join(root,'public/worksheets/transport-play.json'))).find(w=>w.engine==='puzzle'),puzzle={...puzzleRecord,...puzzleRecord.rounds[0]};
assert.equal(spatialComplete(puzzle,{sorted:{}}),false);
assert.equal(spatialComplete(puzzle,{sorted:Object.fromEntries(puzzle.pairs.map(p=>[p.left,p.right]))}),true);
console.log('PASS spatial placement: wrong, replaced, moved, invalid, and solved states');
console.log('PASS route completion: endpoint-only and reverse-order attempts rejected');
console.log('PASS puzzle completion: empty rejected and correct tile placement accepted');

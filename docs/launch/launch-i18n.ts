export const launchMessages: Readonly<Record<LanguageCode, Readonly<Messages>>> = { id, en, zh, ar };

/** Unknown language codes fall back to Indonesian. Format tokens in the caller. */
export function text(lang: string, key: MessageKey): string {
  const code = languages.find((language) => language.code === lang)?.code ?? 'id';
  return launchMessages[code][key];
}
